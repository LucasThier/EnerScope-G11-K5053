import assert from 'node:assert/strict';
import { pathToFileURL } from 'node:url';
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE ? pathToFileURL(process.env.PLAYWRIGHT_MODULE).href : 'playwright');
const browser=await chromium.launch({channel:'chrome',headless:true});
try {
const context=await browser.newContext({viewport:{width:1440,height:900}});
const page=await context.newPage();const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://localhost:5173/login');
await page.locator('input[type="password"]').waitFor();
assert.deepEqual(errors,[]);
const user={id:'u1',mail:'test@example.com',firstName:'Test',lastName:'User',platformRole:'ADMIN'};
await context.addInitScript(user=>{
localStorage.setItem('accessToken','test');localStorage.setItem('refreshToken','test');localStorage.setItem('authUser',JSON.stringify(user));localStorage.setItem('sidebarPinned','true');
},user);
await page.route('**/api/v1/**',route=>{
const path=new URL(route.request().url()).pathname.replace('/api/v1','');
const ok=data=>route.fulfill({json:{success:true,data,message:'OK'}});
if(path==='/auth/refresh')return ok({user,accessToken:'test',refreshToken:'test'});
if(path==='/projects')return ok(['p1','p2'].map(id=>({id,name:id,organizationId:'o1',organizationName:'Org'})));
if(path==='/organizations')return ok([{id:'o1',name:'Org'}]);
if(path==='/projects/p1/versions')return ok([{id:'v1',name:'Version A',nodes:[]}]);
if(path==='/version/v1/diagram')return ok({versionId:'v1',nodes:[],connections:[]});
return ok([]);
});
await page.goto('http://localhost:5173/editor');
await page.locator('option[value="v1"]').waitFor({state:'attached'});
await page.locator('select').nth(1).selectOption('p2');
await page.waitForTimeout(300);
assert.equal(await page.locator('option[value="v1"]').count(),0);
await page.getByRole('link',{name:'Configuración del Escenario',exact:true}).click();
await page.waitForURL('**/projects/p2/scenario-configurations');
await page.getByLabel('Buscar escenario').waitFor();
await page.getByRole('link',{name:/Simulaci.n de Escenarios/,exact:true}).click();
await page.waitForURL('**/projects/p2/simulations');
await page.getByLabel('Buscar escenario').waitFor();
await page.goto('http://localhost:5173/projects/p2/versions/v2/economics/history');
await page.getByRole('heading',{name:'Evaluación del escenario',exact:true}).waitFor();
assert.equal(await page.getByRole('link',{name:'Simulación de Escenarios',exact:true}).getAttribute('aria-current'),'page');
assert.equal(await page.locator('aside').getByRole('link',{name:'Versionado',exact:true}).getAttribute('aria-current'),null);
await page.getByRole('link',{name:/← Simulación de Escenarios/}).click();
await page.waitForURL('**/projects/p2/simulations');
await page.goto('http://localhost:5173/projects/p2/versions/v2/economics/unknown');
await page.waitForURL('**/economics/history');
await page.getByRole('button',{name:'p2',exact:true}).click();
await page.getByRole('listbox').getByRole('button',{name:/p1/}).click();
await page.waitForURL('**/projects/p1/simulations');
await page.goto('http://localhost:5173/projects/p1/versions');
await page.getByRole('button',{name:'Nueva versión',exact:true}).first().waitFor();
assert.equal(await page.locator('aside').getByRole('link',{name:'Versionado',exact:true}).getAttribute('aria-current'),'page');
assert.equal(await page.getByRole('link',{name:'Simulación de Escenarios',exact:true}).getAttribute('aria-current'),null);
await page.getByRole('button',{name:'p1',exact:true}).click();
await page.getByRole('listbox').getByRole('button',{name:/p2/}).click();
await page.waitForURL('**/projects/p2/versions');
await page.getByRole('button',{name:'Nueva versión',exact:true}).first().waitFor();
assert.equal(await page.getByText('Version A',{exact:true}).count(),0);
user.platformRole='USER';
await page.goto('http://localhost:5173/admin/users');await page.waitForURL('**/app');
await page.goto('http://localhost:5173/admin/organizations');await page.waitForURL('**/app');
await page.goto('http://localhost:5173/organizations/o1');await page.waitForURL('**/app');
assert.deepEqual(errors,[]);
console.log('PASS: login bootstrap, authenticated sidebar, editor project switch, configuration and simulation navigation.');
}finally{await browser.close();}
